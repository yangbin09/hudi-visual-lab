function hash(text:string){let h=0;for(const c of text)h=(Math.imul(h,31)+c.charCodeAt(0))>>>0;return h}
function question(id:string,index:number,s:QuestionSpec):QuizQuestion{
  const [prompt,correct,a,b,explanation]=s
  const values=[a,b];values.splice((hash(id)+index)%3,0,correct)
  const options=values.map((text,i)=>({id:`choice-${i}`,text}))
  return {id:`${id}-v${ASSESSMENT_VERSION}-${index}`,prompt,options,requiredForMastery:index===0,answerIds:[options.find(o=>o.text===correct)!.id],explanation}
}
