/**
 * 主题内容层：学习目标 / 前置 / 一句话结论 / 术语卡 / 边界 / 模板映射 / 代表主题旁白。
 *
 * 为什么单独成文件：
 *   - `lessons.ts` 只负责「场景编排」（节点、步骤骨架、operation），内容文案集中在这里，
 *     避免 80 个 `make(...)` 行继续膨胀；
 *   - 所有字段都是 `VisualLesson` 上的**可选**字段，渲染层缺失时按旧行为降级。
 *
 * 旁白写法约定（代表主题 8 个严格执行，其余主题同步去免责化）：
 *   「看到……，因为……，所以……」一句话讲完「现象 → 原因 → 结论」，
 *   长度 45–90 字；术语在该主题首次出现时给 ≤18 字行内定义。
 */
import { glossaryOf } from './glossary'

export interface LessonMeta {
  /** 一句话学习目标（学生视角） */
  objective: string
  /** 前置知识 / 术语 */
  prerequisites: string[]
  /** 一句话关键结论 */
  takeaway: string
  /** 本课术语卡（≤4 个，用术语表里的 term 名，渲染时展开 def） */
  glossary: string[]
  /** 本主题边界：可执行的未确认信息，1–2 条 */
  limitations: string[]
  /** 真实存在的模板 id（src/engine/templates 内） */
  templateIds: string[]
}

/** 把术语名展开成 { term, def }；找不到时退化为 term 自身，保证渲染不崩 */
export function toGlossary(terms: string[]): { term: string; def: string }[] {
  return terms.map((t) => {
    const entry = glossaryOf(t)
    return { term: entry?.term ?? t, def: entry?.def ?? t }
  })
}

