test('读优化明确跳过 Log，而不是让新值也流入结果',async({page})=>{
  await page.goto('/experiment/Q02')
  await page.getByRole('slider',{name:'动画进度'}).fill('2.7')
  const detail=page.locator('[data-detail="query-versions"]')
  await expect(detail).toContainText('读优化不打开 Log')
  await expect(detail).toContainText('Log 没有参与读取')
  await expect(page.getByRole('button',{name:'结果记录 1001',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'下一步',exact:true}).click()
  await page.getByRole('button',{name:'结果记录 1001',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('100.5')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'跳到结果'}).click()
  await page.getByRole('button',{name:'结果记录 1001',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('200')
})

