import { expect, test } from '@playwright/test'

test('更新一行可以看清 COW 复制的两行，单步停在比较与生成阶段',async({page})=>{
  await page.goto('/experiment/W02')
  await page.getByRole('slider',{name:'动画进度'}).fill('2.23')
  const detail=page.locator('[data-detail="record-versions"]')
  await expect(detail).toContainText('100.5')
  await expect(detail).toContainText('200')
  await expect(detail).toContainText('原样复制')
  await expect(detail).toContainText('20240101100000')
  await page.getByRole('button',{name:'下一步',exact:true}).click()
  await expect(page.getByRole('slider',{name:'动画进度'})).toHaveValue('2.44')
  await expect(page.locator('.lesson-explanation')).toContainText('比较记录版本')
  await page.getByRole('button',{name:'下一步',exact:true}).click()
  await expect(page.locator('.lesson-explanation')).toContainText('其中 2 条原样保留')
  await page.getByRole('button',{name:'下一步',exact:true}).click()
  await expect(detail).toContainText('COMMIT · COMPLETED')
  await page.getByRole('button',{name:'输出记录 1002',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('20240101100010')
  await expect(page.locator('.inspector-raw')).not.toHaveAttribute('open','')
})

