import { expect, test } from '@playwright/test'

test('双路径更新、暂停、回退和合并保持引擎状态一致', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/experiment/B02')
  await expect(page.getByRole('heading', { name: '更新一条记录，文件会怎样变化？' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  if (page.viewportSize()!.width >= 1366) expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true)
  const original = await page.locator('.file-glyph').count()
  await page.getByRole('button', { name: '↑ Upsert 更新记录' }).click()
  await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  const position = await page.getByRole('slider', { name: '动画进度' }).inputValue()
  await page.waitForTimeout(180)
  expect(await page.getByRole('slider', { name: '动画进度' }).inputValue()).toBe(position)
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await page.getByRole('button', { name: '跳过动画' }).click()
  expect(await page.locator('.file-glyph').count()).toBeGreaterThan(original)
  const values = page.locator('.vl-query-value')
  await expect(values.nth(0)).toHaveText('¥ 200')
  await expect(values.nth(1)).toHaveText('¥ 200')
  await expect(values.nth(2)).toHaveText('¥ 200')
  await expect(values.nth(3)).toHaveText('¥ 100.5')
  // Undo the completed presentation frame, then replay without applying a second write.
  await page.getByRole('button', { name: '上一步', exact: true }).click()
  await page.getByRole('button', { name: '上一步', exact: true }).click()
  await expect(values.nth(0)).toHaveText('¥ 100.5')
  await page.getByRole('button', { name: '跳过动画' }).click()
  await page.locator('.file-glyph.old').first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('cell', { name: '100.5', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '① Schedule' }).click()
  await page.getByRole('button', { name: '跳过动画' }).click()
  await expect(page.getByRole('button', { name: '② Compaction' })).toBeEnabled()
  await page.getByRole('button', { name: '② Compaction' }).click()
  await page.getByRole('button', { name: '跳过动画' }).click()
  await expect(values.nth(3)).toHaveText('¥ 200')
  await page.getByRole('button', { name: 'Cleaner', exact: true }).click()
  await page.getByRole('button', { name: '跳过动画' }).click()
  await page.screenshot({ path: `/tmp/hudi-visual-${test.info().project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: '重置实验' }).click()
  await expect(values.nth(0)).toHaveText('¥ 100.5')
  expect(errors).toEqual([])
})

test('减少动态效果与工程师抽屉', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/experiment/B03')
  await page.getByRole('button', { name: '↑ Upsert 更新记录' }).click()
  await expect(page.locator('.vl-query-value').first()).toHaveText('¥ 200')
  await page.getByRole('button', { name: '基础模式' }).click()
  await page.getByRole('button', { name: 'SQL / HDFS / Timeline' }).click()
  await page.getByRole('button', { name: 'SQL', exact: true }).click()
  await expect(page.locator('dialog pre')).toContainText('MERGE')
  await page.getByRole('button', { name: 'Timeline', exact: true }).click()
  await expect(page.locator('dialog')).toContainText('DELTA_COMMIT')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '① Schedule' }).click()
  await page.getByRole('button', { name: '模拟失败' }).click()
  await expect(page.locator('.vl-query-value').nth(3)).toHaveText('¥ 100.5')
  await page.getByRole('button', { name: 'SQL / HDFS / Timeline' }).click()
  await page.getByRole('button', { name: 'Timeline', exact: true }).click()
  await expect(page.locator('dialog')).toContainText('INFLIGHT')
})

