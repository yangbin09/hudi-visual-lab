import { expect, test } from '@playwright/test'

test('学习路径中连续切课、浏览器回退、刷新后恢复精确位置和参数',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/path')
  await page.locator('a[href="/experiment/W02"]').first().click()
  await expect(page.locator('h1')).toHaveText('Upsert 更新全过程')
  await page.getByRole('button',{name:'⚙ 参数',exact:true}).click()
  await page.getByLabel('更新金额',{exact:true}).fill('750')
  await page.getByRole('combobox',{name:/表类型/}).selectOption('MERGE_ON_READ')
  await page.getByRole('button',{name:'应用参数并重置',exact:true}).click()
  const slider=page.getByRole('slider',{name:'动画进度',exact:true})
  await slider.fill('2.44')
  await page.getByRole('button',{name:'数据 / 代码 / 依据 ↗',exact:true}).click()
  await page.locator('.lesson-dock').getByRole('tab',{name:/^代码/}).click()
  await expect(page).toHaveURL(/tab=code/)
  await expect(slider).toHaveValue('2.44')
  await page.locator('a[href="/experiment/W03"]').first().click()
  await expect(page).toHaveURL(/\/experiment\/W03/)
  await expect(page.locator('h1')).toHaveText('Delete 删除全过程')
  await expect(slider).toHaveValue('0')
  await page.goBack()
  await expect(page.locator('h1')).toHaveText('Upsert 更新全过程')
  await expect(slider).toHaveValue('2.44')
  await page.reload()
  await expect(slider).toHaveValue('2.44')
  await page.getByRole('button',{name:'⚙ 参数',exact:true}).click()
  await expect(page.getByLabel('更新金额',{exact:true})).toHaveValue('750')
  await expect(page.getByRole('combobox',{name:/表类型/})).toHaveValue('MERGE_ON_READ')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button',{name:'播放演示',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})

test('自测不能靠全选第一项掌握课程，正确预测后进度持久化',async({page})=>{
  await page.goto('/experiment/W02')
  await page.locator('.lesson-selfcheck summary').click()
  const questions=page.locator('.lesson-selfcheck [data-question-id]')
  await expect(questions).toHaveCount(3)
  for(const q of await questions.all())await q.locator('li button').first().click()
  await page.locator('.lesson-selfcheck').getByRole('button',{name:'提交答案',exact:true}).click()
  await expect(page.locator('.lesson-selfcheck')).toContainText('得分 33 分')
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('hudi-lab-lesson-progress')!).W02.mastered)).toBe(false)
  await page.locator('.lesson-selfcheck').getByRole('button',{name:'重做',exact:true}).click()
  await questions.nth(0).getByRole('button',{name:/它可能仍受历史版本和保留窗口保护/}).click()
  await questions.nth(1).getByRole('button',{name:/3 条$/}).click()
  await questions.nth(2).getByRole('button',{name:/0 个$/}).click()
  await page.locator('.lesson-selfcheck').getByRole('button',{name:'提交答案',exact:true}).click()
  await expect(page.locator('.lesson-selfcheck')).toContainText('得分 100 分')
  await page.getByRole('button',{name:'跳到结果',exact:true}).click()
  await page.locator('a[href="/progress"]').first().click()
  await expect(page.locator('tbody tr').filter({hasText:'W02'})).toContainText('已掌握')
  await page.reload()
  await expect(page.locator('tbody tr').filter({hasText:'W02'})).toContainText('100 分')
})

