import { expect, test } from '@playwright/test'

test('E01 用具体配置解释差异，修改后策略与结论一起改变',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/experiment/E01')
  const scene=page.locator('[data-detail="index-config"]')
  await expect(page.getByLabel('本次作业索引')).toHaveValue('SIMPLE')
  await page.getByRole('button',{name:'跳到结果',exact:true}).click()
  await expect(scene).toContainText('BUCKET ≠ SIMPLE · 不一致')
  await expect(scene).toContainText('不是“算错了桶”')
  await expect(page.locator('.lesson-explanation')).toContainText('SIMPLE 按键匹配位置')
  await page.getByRole('button',{name:'对齐为 BUCKET 并重演'}).click()
  await expect(page.getByLabel('本次作业索引')).toHaveValue('BUCKET')
  await expect(page.getByRole('button',{name:'暂停演示',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'跳到结果',exact:true}).click()
  await expect(scene).toContainText('BUCKET = BUCKET · 一致')
  await expect(scene).toContainText('✓ 配置一致')
  await expect(page.locator('.lesson-explanation')).toContainText('真实作业是否恢复，仍要重跑验证')
  await expect(scene.locator('.ac-error')).toHaveCount(0)
  await page.getByRole('button',{name:'查看本案例分桶计算'}).click()
  await expect(page.getByRole('dialog')).toContainText('1001')
  await expect(page.getByRole('dialog')).toContainText('r26')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button',{name:'查看本案例分桶计算'})).toBeFocused()
  await page.getByLabel('本次作业索引').selectOption('SIMPLE')
  await page.getByRole('button',{name:'跳到结果',exact:true}).click()
  await expect(scene).toContainText('BUCKET ≠ SIMPLE · 不一致')
  await expect(scene).not.toContainText('✓ 配置一致')
  await expect(page.locator('.lesson-explanation')).toContainText(/对齐为 BUCKET 并重演/)
  await page.getByRole('button',{name:'⚙ 参数'}).click()
  await expect(page.getByLabel('机制示意的阻断关口')).toHaveCount(0)
  await page.getByLabel('记录主键',{exact:true}).fill('1002')
  await page.getByLabel('Bucket 数量',{exact:true}).fill('3')
  await page.getByRole('button',{name:'应用参数并重置'}).click()
  await expect(scene).toContainText('1002')
  await expect(scene).toContainText('% 3')
  await expect(page.getByLabel('本次作业索引')).toHaveValue('SIMPLE')
  const box=await scene.boundingBox()
  expect(box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  expect(errors).toEqual([])
})

test('E01 单步停在策略计算细节，拖动不会自动修改配置',async({page})=>{
  await page.goto('/experiment/E01')
  await page.getByRole('slider',{name:'动画进度'}).fill('2.99')
  const next=page.getByRole('button',{name:'下一步',exact:true})
  await next.click()
  await expect(page.getByRole('slider',{name:'动画进度'})).toHaveValue('3.12')
  await expect(page.locator('.lesson-explanation')).toContainText('输入相同的主键 1001')
  await next.click()
  await expect(page.locator('.lesson-explanation')).toContainText('当前采用 SIMPLE')
  await next.click()
  await expect(page.locator('.lesson-explanation')).toContainText('匹配相同 key，得到文件 B')
  await next.click()
  await expect(page.locator('[data-detail="index-config"]')).toContainText('✓ 文件 B')
  await expect(page.getByLabel('本次作业索引')).toHaveValue('SIMPLE')
  await page.getByLabel('本次作业索引').selectOption('BUCKET')
  await page.getByRole('slider',{name:'动画进度'}).fill('3.6')
  await expect(page.locator('.lesson-explanation')).toContainText('余数就是桶号')
  await page.getByRole('button',{name:'切换深浅主题'}).click()
  await expect(page.locator('.visual-lab')).toHaveClass(/vl-light/)
  await next.click()
  await expect(page.locator('[data-detail="index-config"]')).toContainText('✓ 桶 3')
})
